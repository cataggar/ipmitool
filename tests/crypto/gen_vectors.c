/* lanplus_crypt.c: RAKP 1-4 key derivation                             */
/* ------------------------------------------------------------------ */

struct rakp_case {
	const char *name;
	uint8_t auth_alg;
	uint8_t integrity_alg;
	const char *username;
	const char *password;
	const char *kg;
	const char *oem;
	uint8_t requested_role;
	uint8_t privlvl;
};

static void gen_rakp_case(const struct rakp_case *tc)
{
	struct ipmi_session session;
	struct ipmi_intf intf;
	uint8_t bmc_mac[IPMI_MAX_MD_SIZE];
	uint8_t rakp3[IPMI_MAX_MD_SIZE];
	uint32_t rakp3_len = 0;
	int matches;

	memset(&session, 0, sizeof(session));
	memset(&intf, 0, sizeof(intf));

	active_oem = tc->oem;

	snprintf((char *)intf.ssn_params.username,
	         sizeof(intf.ssn_params.username), "%s", tc->username);
	snprintf((char *)session.authcode, sizeof(session.authcode), "%s",
	         tc->password);
	snprintf((char *)intf.ssn_params.kg, sizeof(intf.ssn_params.kg), "%s",
	         tc->kg);
	intf.ssn_params.privlvl = tc->privlvl;

	session.v2_data.auth_alg = tc->auth_alg;
	session.v2_data.integrity_alg = tc->integrity_alg;
	session.v2_data.crypt_alg = IPMI_CRYPT_AES_CBC_128;
	session.v2_data.console_id = 0xa0a1a2a3u;
	session.v2_data.bmc_id = 0xb0b1b2b3u;
	session.v2_data.requested_role = tc->requested_role;
	fill(session.v2_data.console_rand, 16, 101);
	fill(session.v2_data.bmc_rand, 16, 102);
	fill(session.v2_data.bmc_guid, 16, 103);

	emit_case(tc->name);
	emit_int("auth_alg", tc->auth_alg);
	emit_int("integrity_alg", tc->integrity_alg);
	emit_str("username", tc->username);
	emit_str("oem", tc->oem ? tc->oem : "");
	emit_int("requested_role", tc->requested_role);
	emit_int("privlvl", tc->privlvl);
	emit_hex("console_id", (const uint8_t *)&session.v2_data.console_id, 4);
	emit_hex("bmc_id", (const uint8_t *)&session.v2_data.bmc_id, 4);
	emit_hex("console_rand", session.v2_data.console_rand, 16);
	emit_hex("bmc_rand", session.v2_data.bmc_rand, 16);
	emit_hex("bmc_guid", session.v2_data.bmc_guid, 16);
	emit_hex("session_authcode", session.authcode, IPMI_AUTHCODE_BUFFER_SIZE);
	emit_hex("session_kg", intf.ssn_params.kg, IPMI_AUTHCODE_BUFFER_SIZE);

	/* RAKP 2: run once with a bogus MAC to capture what the console computes. */
	memset(bmc_mac, 0, sizeof(bmc_mac));
	capture_reset();
	matches = lanplus_rakp2_hmac_matches(&session, bmc_mac, &intf);
	emit_int("rakp2_matches_zero", matches);
	if (tc->auth_alg != IPMI_AUTH_RAKP_NONE) {
		emit_capture("rakp2_input", ">> rakp2 mac input buffer");
		emit_capture("rakp2_key", ">> rakp2 mac key");
		emit_capture("rakp2_mac", ">> rakp2 mac as computed by the remote console");
		{
			int len;
			const uint8_t *mac = capture_get(
				">> rakp2 mac as computed by the remote console", &len);
			memcpy(bmc_mac, mac, len);
		}
		capture_reset();
		emit_int("rakp2_matches_real",
		         lanplus_rakp2_hmac_matches(&session, bmc_mac, &intf));
	}

	/* RAKP 3 */
	capture_reset();
	memset(rakp3, 0, sizeof(rakp3));
	emit_int("rakp3_rc",
	         lanplus_generate_rakp3_authcode(rakp3, &session, &rakp3_len, &intf));
	if (tc->auth_alg != IPMI_AUTH_RAKP_NONE)
		emit_capture("rakp3_input", ">> rakp3 mac input buffer");
	emit_int("rakp3_len", rakp3_len);
	emit_hex("rakp3_mac", rakp3, (int)rakp3_len);

	/* SIK, K1, K2 */
	capture_reset();
	emit_int("sik_rc", lanplus_generate_sik(&session, &intf));
	if (tc->auth_alg != IPMI_AUTH_RAKP_NONE)
		emit_capture("sik_input", "session integrity key input");
	emit_int("sik_len", session.v2_data.sik_len);
	emit_hex("sik", session.v2_data.sik, session.v2_data.sik_len);

	capture_reset();
	emit_int("k1_rc", lanplus_generate_k1(&session));
	emit_int("k1_len", session.v2_data.k1_len);
	/* With IPMI_AUTH_RAKP_NONE the C fills 20 bytes of K1 but never sets
	 * k1_len, so the 20 bytes are recorded separately from the length. */
	emit_hex("k1", session.v2_data.k1, IPMI_MAX_MD_SIZE);

	capture_reset();
	emit_int("k2_rc", lanplus_generate_k2(&session));
	emit_int("k2_len", session.v2_data.k2_len);
	emit_hex("k2", session.v2_data.k2, IPMI_MAX_MD_SIZE);

	/* RAKP 4, keyed with the SIK just derived. */
	memset(bmc_mac, 0, sizeof(bmc_mac));
	capture_reset();
	matches = lanplus_rakp4_hmac_matches(&session, bmc_mac, &intf);
	emit_int("rakp4_matches_zero", matches);
	if (tc->auth_alg != IPMI_AUTH_RAKP_NONE) {
		emit_capture("rakp4_input", ">> rakp4 mac input buffer");
		emit_capture("rakp4_key", ">> rakp4 mac key (sik)");
		emit_capture("rakp4_mac", ">> rakp4 mac as computed by the remote console");
		{
			int len;
			const uint8_t *mac = capture_get(
				">> rakp4 mac as computed by the remote console", &len);
			memcpy(bmc_mac, mac, len);
		}
		capture_reset();
		emit_int("rakp4_matches_real",
		         lanplus_rakp4_hmac_matches(&session, bmc_mac, &intf));
	}

	/* Integrity check value over a synthetic RMCP+ packet. */
	if (tc->integrity_alg != IPMI_INTEGRITY_NONE) {
		struct ipmi_rs rs;
		uint32_t authcode_length;
		uint8_t generated[IPMI_MAX_MD_SIZE];
		uint32_t generated_len = 0;
		int payload_len = 96;

		switch (tc->integrity_alg) {
		case IPMI_INTEGRITY_HMAC_SHA1_96:
			authcode_length = IPMI_SHA1_AUTHCODE_SIZE;
			break;
		case IPMI_INTEGRITY_HMAC_MD5_128:
			authcode_length = IPMI_HMAC_MD5_AUTHCODE_SIZE;
			break;
		default:
			authcode_length = IPMI_HMAC_SHA256_AUTHCODE_SIZE;
			break;
		}

		memset(&rs, 0, sizeof(rs));
		fill(rs.data, payload_len, 55);
		rs.data_len = payload_len;
		rs.session.authtype = IPMI_SESSION_AUTHTYPE_RMCP_PLUS;
		rs.session.bAuthenticated = 1;
		session.v2_data.session_state = LANPLUS_STATE_ACTIVE;

		/* Compute the expected authcode with the same primitive the C
		 * uses, then splice it into the packet so the check passes. */
		lanplus_HMAC(session.v2_data.integrity_alg,
		             session.v2_data.k1, session.v2_data.k1_len,
		             rs.data + IPMI_LANPLUS_OFFSET_AUTHTYPE,
		             rs.data_len - IPMI_LANPLUS_OFFSET_AUTHTYPE
		                 - (int)authcode_length,
		             generated, &generated_len);
		memcpy(rs.data + rs.data_len - authcode_length, generated,
		       authcode_length);

		capture_reset();
		emit_int("integrity_authcode_length", authcode_length);
		emit_hex("integrity_packet", rs.data, rs.data_len);
		emit_hex("integrity_authcode", generated, (int)generated_len);
		emit_int("integrity_valid",
		         lanplus_has_valid_auth_code(&rs, &session));

		/* Flip one byte of the packet body: the check must now fail. */
		rs.data[10] ^= 0xff;
		capture_reset();
		emit_int("integrity_valid_tampered",
		         lanplus_has_valid_auth_code(&rs, &session));
	}

	active_oem = NULL;
}

