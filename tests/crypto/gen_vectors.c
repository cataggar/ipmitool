/*
 * Crypto parity vector generator.
 *
 * This links the *original OpenSSL-backed C* crypto sources -- `md5.c`,
 * `auth.c`, `lanplus_crypt_impl.c` and `lanplus_crypt.c` -- and dumps every
 * input/output pair the Zig `std.crypto` ports have to reproduce bit for bit.
 * The fixtures it writes live in `tests/crypto/vectors/` and are the reference
 * the Zig unit tests in `src/zig/crypto/vectors_test.zig` assert against.
 *
 *     zig build gen-crypto-vectors      # regenerates tests/crypto/vectors/
 *
 * It is deliberately not part of `zig build` or `zig build test`: it is the
 * only thing left in the tree that needs libcrypto, and it exists so the
 * vectors can be re-derived from the C at any point during the migration.
 *
 * The RAKP intermediates (the exact bytes hashed for RAKP 2/3/4, the SIK and
 * K1/K2) are not returned by the C functions, so they are captured through the
 * `printbuf()` calls the C already makes at `verbose > 2`: this file provides
 * its own `printbuf` that records the buffers instead of printing them.  That
 * way the vectors are the real intermediate state of the C implementation
 * rather than a second-guess of it.
 */

